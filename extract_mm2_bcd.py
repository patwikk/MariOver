    # -----------------------------------------------------------------------
    # ReGrdCode — update GroundNode for slopes
    # -----------------------------------------------------------------------

    def re_grd_code(self):
        for obj in self.level["objects"]:
            objW = obj["w"]
            objH = obj["h"]
            objFlag = obj["flag"]
            objX = obj["x"]
            objY = obj["y"]
            obj_id = obj["id"]

            if obj_id == 87:  # slight slope
                CX = round(-0.5 + objX / 160.0)
                CY = round(-0.5 + objY / 160.0)
                if (objFlag // 0x100000) % 2 == 0:
                    # left slope
                    v = self._gn(CX+1, CY+1)
                    if v == 0: self._gn_set(CX+1, CY+1, 23)
                    elif v in (6,20,8,22): self._gn_set(CX+1, CY+1, 1)

                    v = self._gn(CX+objW, CY+objH)
                    if v == 0: self._gn_set(CX+objW, CY+objH, 20)
                    elif v in (9,23,7,21): self._gn_set(CX+objW, CY+objH, 1)

                    j = 1
                    while j <= objW - 2:
                        self._gn_set(CX+1+j, CY+1+(j//2)+1, 19)
                        v = self._gn(CX+1+j, CY+1+(j//2))
                        if v in (0,6,20): self._gn_set(CX+1+j, CY+1+(j//2), 12)
                        v = self._gn(int(CX+2.0+j), CY+1+(j//2)+1)
                        if v in (0,9,23): self._gn_set(int(CX+2.0+j), CY+1+(j//2)+1, 15)
                        self._gn_set(int(CX+2.0+j), CY+1+(j//2), 16)
                        j += 2
                else:
                    # right slope
                    v = self._gn(CX+1, CY+objH)
                    if v == 0: self._gn_set(CX+1, CY+objH, 21)
                    elif v in (6,8,20,22): self._gn_set(CX+1, CY+objH, 1)

                    v = self._gn(CX+objW, CY+1)
                    if v == 0: self._gn_set(CX+objW, CY+1, 22)
                    elif v in (9,7,23,21): self._gn_set(CX+objW, CY+1, 1)

                    j = 1
                    while j <= objW - 2:
                        self._gn_set(CX+1+j, CY+objH-(j//2)-1, 17)
                        v = self._gn(CX+1+j, CY+objH-(j//2))
                        if v in (0,22,8): self._gn_set(CX+1+j, CY+objH-(j//2), 14)
                        v = self._gn(int(CX+2.0+j), CY+objH-(j//2)-1)
                        if v in (0,21,7): self._gn_set(int(CX+2.0+j), CY+objH-(j//2)-1, 13)
                        self._gn_set(int(CX+2.0+j), CY+objH-(j//2), 18)
                        j += 2

            elif obj_id == 88:  # steep slope
                CX = round(-0.5 + objX / 160.0)
                CY = round(-0.5 + objY / 160.0)
                if (objFlag // 0x100000) % 2 == 0:
                    # left slope
                    v = self._gn(CX+1, CY+1)
                    if v == 0: self._gn_set(CX+1, CY+1, 9)
                    elif v in (6,8,20,22): self._gn_set(CX+1, CY+1, 1)

                    v = self._gn(CX+objW, CY+objH)
                    if v == 0: self._gn_set(CX+objW, CY+objH, 6)
                    elif v in (9,7,23,21): self._gn_set(CX+objW, CY+objH, 1)

                    for j in range(1, objW - 1):
                        v = self._gn(CX+1+j, CY+1+j)
                        if v in (0,9,23): self._gn_set(CX+1+j, CY+1+j, 5)
                        v = self._gn(CX+1+j, CY+j)
                        if v in (0,6,20): self._gn_set(CX+1+j, CY+j, 2)
                else:
                    # right slope
                    v = self._gn(CX+1, CY+objH)
                    if v == 0: self._gn_set(CX+1, CY+objH, 7)
                    elif v in (6,8,20,22): self._gn_set(CX+1, CY+objH, 1)

                    v = self._gn(CX+objW, CY+1)
                    if v == 0: self._gn_set(CX+objW, CY+1, 8)
                    elif v in (9,7,23,21): self._gn_set(CX+objW, CY+1, 1)

                    for j in range(1, objW - 1):
                        v = self._gn(CX+1+j, CY+objW-j)
                        if v in (0,8,22): self._gn_set(CX+1+j, CY+objW-j, 4)
                        v = self._gn(CX+1+j, CY+objW-1-j)
                        if v in (0,7,21): self._gn_set(CX+1+j, CY+objW-1-j, 3)

        # Propagate slope constraints (3 passes)
        for _ in range(3):
            for i in range(self.W + 1):
                for j in range(self.H + 1):
                    v = self._gn(i+1, j+1)
                    if v in (2, 16):
                        if self._gn(i+2, j+1) > 0 or self._gn(i+1, j) > 0:
                            self._gn_set(i+1, j+1, 1)
                    elif v in (3, 17):
                        if self._gn(i, j+1) > 0 or self._gn(i+1, j) > 0:
                            self._gn_set(i+1, j+1, 1)
                    elif v in (4, 18):
                        if self._gn(i+2, j+1) > 0 or self._gn(i+1, j+2) > 0:
                            self._gn_set(i+1, j+1, 1)
                    elif v in (5, 19):
                        if self._gn(i, j+1) > 0 or self._gn(i+1, j+2) > 0:
                            self._gn_set(i+1, j+1, 1)
                    elif v == 12:
                        if self._gn(i+1, j) > 0 or self._gn(i+2, j+1) == 1:
                            self._gn_set(i+1, j+1, 1)
                    elif v == 13:
                        if self._gn(i+1, j) > 0 or self._gn(i, j+1) == 1:
                            self._gn_set(i+1, j+1, 1)
                    elif v == 14:
                        if self._gn(i+1, j+2) > 0 or self._gn(i+2, j+1) == 1:
                            self._gn_set(i+1, j+1, 1)
                    elif v == 15:
                        if self._gn(i+1, j+2) > 0 or self._gn(i, j+1) == 1:
                            self._gn_set(i+1, j+1, 1)


    def draw_fire(self):
        Zm = self.Zm
        H = self.H
        gs = self.gamestyle

        for obj in self.level["objects"]:
            if obj["id"] != 54:
                continue
            objW = obj["w"]
            objH = obj["h"]
            objFlag = obj["flag"]
            objX = obj["x"]
            objY = obj["y"]

            flag_low = objFlag % 0x100
            path_map = {
                0x40: gs | OBJ_54A1,
                0x48: gs | OBJ_54A3,
                0x50: gs | OBJ_54A5,
                0x58: gs | OBJ_54A7,
                0x44: gs | OBJ_54A2,
                0x4C: gs | OBJ_54A4,
                0x54: gs | OBJ_54A6,
                0x5C: gs | OBJ_54A8,
            }

            def _xy_for_dir(fl):
                if fl in (0x40, 0x44):
                    return ((-objW/2.0 + objX/160.0)*Zm,
                            (H-3)*Zm - (objH-0.5+objY/160.0)*Zm,
                            Zm*objW, 3*Zm*objH)
                elif fl in (0x48, 0x4C):
                    return ((-objW/2.0+1+objX/160.0)*Zm,
                            H*Zm - (objH-0.5+objY/160.0)*Zm,
                            3*Zm*objW, Zm*objH)
                elif fl in (0x50, 0x54):
                    return ((-objW/2.0+objX/160.0)*Zm,
                            (H+1)*Zm - (objH-0.5+objY/160.0)*Zm,
                            Zm*objW, 3*Zm*objH)
                elif fl in (0x58, 0x5C):
                    return ((-objW/2.0-3+objX/160.0)*Zm,
                            H*Zm - (objH-0.5+objY/160.0)*Zm,
                            3*Zm*objW, Zm*objH)
                return None

            if flag_low in path_map:
                p = path_map[flag_low]
                coords = _xy_for_dir(flag_low)
                if coords:
                    self.draw_image_opacity(p, 0.5, *coords)


    def _setup_ground_node(self):
        """Pre-populate GroundNode from ground tiles and goal/start columns."""
        for g in self.level["ground"]:
            x, y = g["x"], g["y"]
            self.ground_node[x + 1][y + 1] = 1

        if self.is_overworld:
            goal_x = self.goal_x
            goal_y = self.goal_y
            start_y = self.start_y
            j_start = round((goal_x - 5) / 10.0)
            j_end   = int((goal_x - 5) / 10.0 + 9)
            for j in range(j_start, j_end + 1):
                for i in range(goal_y):
                    self.ground_node[j + 1][i + 1] = 1
            for j in range(7):
                for i in range(start_y):
                    self.ground_node[j + 1][i + 1] = 1

    def _setup_track_node(self):
        """Pre-populate TrackNode from track data."""
        for trk in self.level.get("tracks", []):
            t = trk["type"]
            tx = trk["x"]
            ty = trk["y"]
            f0 = trk.get("f0", 0)
            f1 = trk.get("f1", 0)
            f2 = trk.get("f2", 0)
            lid = trk.get("lid", 0)
            self.obj_link_type[lid] = 59

            # mark track nodes same as C++
            if t == 0:
                self._tn_inc(tx,     ty + 1)
                self._tn_inc(tx + 2, ty + 1)
            elif t == 1:
                self._tn_inc(tx + 1, ty + 2)
                self._tn_inc(tx + 1, ty)
            elif t in (2, 4, 5):
                self._tn_inc(tx,     ty + 2)
                self._tn_inc(tx + 2, ty)
            elif t in (3, 6, 7):
                self._tn_inc(tx + 2, ty + 2)
                self._tn_inc(tx,     ty)
            elif t == 8:
                self._tn_inc(tx,     ty + 2)
                self._tn_inc(tx + 4, ty)
                self._tn_inc(tx + 4, ty + 4)
            elif t == 9:
                self._tn_inc(tx,     ty)
                self._tn_inc(tx,     ty + 4)
                self._tn_inc(tx + 4, ty + 2)
            elif t == 10:
                self._tn_inc(tx,     ty)
                self._tn_inc(tx + 2, ty + 4)
                self._tn_inc(tx + 4, ty)
            elif t == 11:
                self._tn_inc(tx + 2, ty)
                self._tn_inc(tx,     ty + 4)
                self._tn_inc(tx + 4, ty + 4)
            elif t == 12:
                self._tn_inc(tx,     ty + 2)
                self._tn_inc(tx + 4, ty)
                self._tn_inc(tx + 4, ty + 4)
            elif t == 13:
                self._tn_inc(tx,     ty)
                self._tn_inc(tx,     ty + 4)
                self._tn_inc(tx + 4, ty + 2)
            elif t == 14:
                self._tn_inc(tx,     ty)
                self._tn_inc(tx + 4, ty)
                self._tn_inc(tx + 2, ty + 4)
            elif t == 15:
                self._tn_inc(tx + 2, ty)
                self._tn_inc(tx,     ty + 4)
                self._tn_inc(tx + 4, ty + 4)

    def _tn_inc(self, x, y):
        if 0 <= x < len(self.track_node) and 0 <= y < len(self.track_node[0]):
            self.track_node[x][y] += 1

    def _gn(self, x, y):
        """Safe ground_node read."""
        if 0 <= x < len(self.ground_node) and 0 <= y < len(self.ground_node[0]):
            return self.ground_node[x][y]
        return 0

    def _gn_set(self, x, y, v):
        if 0 <= x < len(self.ground_node) and 0 <= y < len(self.ground_node[0]):
            self.ground_node[x][y] = v

    # -----------------------------------------------------------------------
    # Instruction emitters
    # -----------------------------------------------------------------------

    def draw_tile(self, tile_x, tile_y, tile_w, tile_h, x, y, target_w, target_h):
        self.instructions.append({
            "path": self.tilesheet_path,
            "is_tile": True,
            "x": int(x),
            "y": int(y),
            "target_width": int(target_w),
            "target_height": int(target_h),
            "tile_x": int(tile_x),
            "tile_y": int(tile_y),
            "tile_w": int(tile_w),
            "tile_h": int(tile_h),
        })


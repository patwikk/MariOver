def decompress_level_data(raw) -> bytes:
    if isinstance(raw, (list, bytearray)):
        raw = bytes(raw)
    try:
        return zlib.decompress(raw)
    except zlib.error:
        pass
    try:
        return zlib.decompress(raw, 16 + zlib.MAX_WBITS)
    except zlib.error as e:
        raise ValueError(f"Cannot decompress: {e}") from e


def extract_levels(output_dir: str, limit=None, streaming=True, data_id_filter=None,
                   write_bcd=True, write_json=False, is_overworld=True):
    from datasets import load_dataset

    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    print(f"Loading dataset (streaming={streaming}) …")
    ds = load_dataset("TheGreatRambler/mm2_level", streaming=streaming, split="train")

    saved = skipped = errors = 0

    for row in ds:
        data_id = row["data_id"]
        if data_id_filter and data_id not in data_id_filter:
            continue

        raw = row["level_data"]
        if raw is None:
            skipped += 1
            continue

        try:
            plaintext = decompress_level_data(raw)
        except ValueError as e:
            print(f"  [WARN] {data_id}: decompress error: {e}")
            errors += 1
            continue

        if len(plaintext) != PAYLOAD_SIZE:
            print(f"  [WARN] {data_id}: unexpected size {len(plaintext)}, skipping")
            errors += 1
            continue

        if write_bcd:
            try:
                bcd = build_bcd(plaintext)
                (out / f"{data_id}.bcd").write_bytes(bcd)
            except Exception as e:
                print(f"  [WARN] {data_id}: encrypt error: {e}")
                errors += 1
                continue

        if write_json:
            try:
                level_json = parse_level_json(plaintext, data_id=data_id,
                                              is_overworld=is_overworld)
                json_path = out / f"{data_id}.json"
                json_path.write_text(
                    json.dumps(level_json, ensure_ascii=False, indent=2),
                    encoding="utf-8",
                )
                n_instr = len(level_json.get("drawing_instructions", []))
                print(f"  Saved JSON for {data_id} ({n_instr} drawing instructions)")
            except Exception as e:
                print(f"  [WARN] {data_id}: json error: {e}")
                errors += 1

        saved += 1
        if saved % 100 == 0 or saved == 1:
            print(f"  Saved {saved} levels … (last: {data_id})")

        if limit and saved >= limit:
            break

    print(f"\nDone. Saved: {saved} | Skipped: {skipped} | Errors: {errors}")



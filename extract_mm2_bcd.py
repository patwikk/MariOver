def parse_level_json(plaintext: bytes, data_id: int = None,
                     is_overworld: bool = True) -> dict:
    r = BinaryReader(plaintext)

    start_y = r.u1()
    goal_y = r.u1()
    goal_x = r.s2()
    timer = r.s2()
    clear_condition_magnitude = r.s2()
    year = r.s2()
    month = r.s1()
    day = r.s1()
    hour = r.s1()
    minute = r.s1()
    autoscroll_speed_raw = r.u1()
    clear_condition_category_raw = r.u1()
    clear_condition = r.s4()
    unk_gamever = r.s4()
    unk_management_flags = r.s4()
    clear_attempts = r.s4()
    clear_time = r.s4()
    unk_creation_id = r.u4()
    unk_upload_id = r.s8()
    game_version_raw = r.s4()

    r.skip(0xBD)

    gamestyle_raw = r.s2()
    unk2 = r.u1()
    name = r.str_utf16le(0x42)
    description = r.str_utf16le(0xCA)

    # Map Header
    theme_raw = r.u1()
    autoscroll_type_raw = r.u1()
    boundary_type_raw = r.u1()
    orientation_raw = r.u1()
    liquid_end_height = r.u1()
    liquid_mode_raw = r.u1()
    liquid_speed_raw = r.u1()
    liquid_start_height = r.u1()
    boundary_right = r.s4()
    boundary_top = r.s4()
    boundary_left = r.s4()
    boundary_bottom = r.s4()
    unk_flag = r.s4()

    object_count = r.s4()
    sound_effect_count = r.s4()
    snake_block_count = r.s4()
    clear_pipe_count = r.s4()
    piranha_creeper_count = r.s4()
    exclamation_mark_block_count = r.s4()
    track_block_count = r.s4()
    unk1 = r.s4()
    ground_count = r.s4()
    track_count = r.s4()
    ice_count = r.s4()

    objects = []
    for _ in range(object_count):
        obj = parse_obj(r)
        objects.append({
            "name":      obj["name"],
            "x":         obj["x"],
            "y":         obj["y"],
            "w":         obj["w"],
            "h":         obj["h"],
            "flag":      obj["flag"],
            "cflag":     obj["cflag"],
            "ex":        obj["ex"],
            "id":        obj["id"],
            "cid":       obj["cid"],
            "lid":       obj["lid"],
            "sid":       obj["sid"],
            "link_type": obj["link_type"],
        })

    if objects:
        max_y = max((o["y"] for o in objects), default=0)
        max_x = max((o["x"] for o in objects), default=0)
        objects.sort(key=lambda o: o["x"] + (max_y - o["y"] - o.get("h", 1) * 160) * max_x)

    # Ground (full fixed-size array: 4000 entries)
    ground = []
    for _ in range(ground_count):
        ground.append({
            "x":   r.u1(),
            "y":   r.u1(),
            "id":  r.u1(),
            "bid": r.u1()
        })
    # Skip remaining ground slots
    r.skip((4000 - ground_count) * 4)

    # Tracks (full fixed-size array: 1500 entries)
    tracks_raw = []
    for _ in range(track_count):
        un   = r.u2()
        flag = r.u1()
        tx   = r.u1()
        ty   = r.u1()
        ttype = r.u1()
        lid  = r.u2()
        k0   = r.u2()
        k1   = r.u2()
        # Compute f0/f1/f2 same as LevelParser.cpp
        f0 = f1 = f2 = 0
        if ttype == 0:
            f0 = ((k0 + 0x10000) // 0x80) % 2
            f1 = ((k1 + 0x10000) // 0x80) % 2
        elif ttype == 1:
            f0 = ((k0 + 0x10000) // 0x80) % 2
            f1 = ((k1 + 0x10000) // 0x80) % 2
        elif ttype in (2, 4, 5):
            f0 = ((k0 + 0x10000) // 0x80) % 2
            f1 = ((k1 + 0x10000) // 0x80) % 2
        elif ttype in (3, 6, 7):
            f0 = ((k0 + 0x10000) // 0x80) % 2
            f1 = ((k1 + 0x10000) // 0x80) % 2
        elif ttype == 8:
            f0 = ((k1 + 0x10000) // 0x80) % 2
            f1 = ((k0 + 0x10000) // 0x80) % 2
            f2 = ((k0 + 0x10000) // 0x8000) % 2
        elif ttype == 9:
            f0 = ((k1 + 0x10000) // 0x40) % 2
            f1 = ((k1 + 0x10000) // 0x2) % 2
            f2 = ((k0 + 0x10000) // 0x80) % 2
        elif ttype == 10:
            f0 = (1 - ((k0 + 0x10000) // 0x4000) % 2)
            f1 = ((k1 + 0x10000) // 0x40) % 2
            f2 = ((k0 + 0x10000) // 0x80) % 2
        elif ttype == 11:
            f0 = ((k0 + 0x10000) // 0x80) % 2
            f1 = ((k1 + 0x10000) // 0x2) % 2
            f2 = ((k1 + 0x10000) // 0x40) % 2
        elif ttype == 12:
            f0 = ((k1 + 0x10000) // 0x800) % 2
            f1 = ((k0 + 0x10000) // 0x80) % 2
            f2 = ((k0 + 0x10000) // 0x1000) % 2
        elif ttype == 13:
            f0 = ((k1 + 0x10000) // 0x800) % 2
            f1 = ((k0 + 0x10000) // 0x1000) % 2
            f2 = ((k0 + 0x10000) // 0x80) % 2
        elif ttype == 14:
            f0 = ((k0 + 0x10000) // 0x1000) % 2
            f1 = ((k1 + 0x10000) // 0x800) % 2
            f2 = ((k0 + 0x10000) // 0x80) % 2
        elif ttype == 15:
            f0 = ((k0 + 0x10000) // 0x80) % 2
            f1 = ((k0 + 0x10000) // 0x1000) % 2
            f2 = ((k1 + 0x10000) // 0x800) % 2
        # Adjust x/y like C++
        if tx == 255: tx = 0
        else: tx = (tx + 1) & 0xFF
        if ty == 255: ty = 0
        else: ty = (ty + 1) & 0xFF
        tracks_raw.append({
            "unk1": un, "flags": flag,
            "x": tx, "y": ty, "type": ttype,
            "lid": lid, "k0": k0, "k1": k1,
            "f0": f0, "f1": f1, "f2": f2,
        })
    r.skip((1500 - track_count) * 10)  # each track is 10 bytes

    # Icicles (fixed: 300 entries)
    icicles = []
    for _ in range(ice_count):
        icicles.append({"x": r.u1(), "y": r.u1(), "type": r.u1(), "unk1": r.u1()})
    r.skip((300 - ice_count) * 4)

    # Sounds (fixed: 300 entries)
    sounds = []
    for _ in range(sound_effect_count):
        sounds.append({"id": r.u1(), "x": r.u1(), "y": r.u1(), "unk1": r.u1()})
    r.skip((300 - sound_effect_count) * 4)

    # Snakes (fixed: 5 entries, 120 nodes each)
    snakes = []
    for i in range(snake_block_count):
        index = r.u1()
        node_count = r.u1()
        r.u2()
        nodes = []
        for j in range(120):
            nd_index = r.u2()
            nd_dir = r.u2()
            r.u4()
            if j < node_count:
                nodes.append({"index": nd_index, "direction": nd_dir})
        snakes.append({"index": index, "node_count": node_count, "nodes": nodes})
    for _ in range(5 - snake_block_count):
        r.skip(1 + 1 + 2 + 120 * 8)

    # Clear Pipes (fixed: 200 entries, 36 nodes each)
    clear_pipes = []
    for i in range(clear_pipe_count):
        index = r.u1()
        node_count = r.u1()
        unk_cp = r.u2()
        nodes = []
        for j in range(36):
            nd = {
                "type": r.u1(), "index": r.u1(),
                "x": r.u1(), "y": r.u1(),
                "w": r.u1(), "h": r.u1(),
                "unk1": r.u1(), "direction": r.u1()
            }
            if unk_cp != 0 and j < node_count:
                nodes.append(nd)
        clear_pipes.append({"index": index, "node_count": node_count, "nodes": nodes})
    for _ in range(200 - clear_pipe_count):
        r.skip(1 + 1 + 2 + 36 * 8)

    # Piranha Creepers (fixed: 10 entries, 20 nodes each)
    piranha_creepers = []
    for i in range(piranha_creeper_count):
        unk_pc = r.u1()
        index = r.u1()
        node_count = r.u1()
        r.u1()
        nodes = []
        for j in range(20):
            nd_unk = r.u1()
            nd_dir = r.u1()
            r.u2()
            if j < node_count:
                nodes.append(nd_dir)
        piranha_creepers.append({"index": index, "node_count": node_count, "nodes": nodes})
    for _ in range(10 - piranha_creeper_count):
        r.skip(1 + 1 + 1 + 1 + 20 * 4)

    # Exclamation Blocks (fixed: 10 entries, 10 nodes each)
    exclamation_blocks = []
    for i in range(exclamation_mark_block_count):
        r.u1()
        index = r.u1()
        node_count = r.u1()
        r.u1()
        nodes = []
        for j in range(10):
            nd = {"unk1": r.u1(), "direction": r.u1(), "unk2": r.u2()}
            if j < node_count:
                nodes.append(nd)
        exclamation_blocks.append({"index": index, "node_count": node_count, "nodes": nodes})
    for _ in range(10 - exclamation_mark_block_count):
        r.skip(1 + 1 + 1 + 1 + 10 * 4)

    # Track Blocks (fixed: 10 entries, 10 nodes each)
    track_blocks = []
    for i in range(track_block_count):
        r.u1()
        index = r.u1()
        node_count = r.u1()
        r.u1()
        nodes = []
        for j in range(10):
            nd = {"unk1": r.u1(), "direction": r.u1(), "unk2": r.u2()}
            if j < node_count:
                nodes.append(nd)
        track_blocks.append({"index": index, "node_count": node_count, "nodes": nodes})
    for _ in range(10 - track_block_count):
        r.skip(1 + 1 + 1 + 1 + 10 * 4)

    # Build partial level dict (needed by drawing instructions generator)
    level = {
        "name": name,
        "description": description,
        "gamestyle": GAMESTYLE.get(gamestyle_raw, "Unknown"),
        "gamestyle_raw": gamestyle_raw,
        "theme": THEME.get(theme_raw, "Unknown"),
        "theme_raw": theme_raw,
        "is_overworld": is_overworld,
        "night_time": unk_flag == 1,
        "clear_time": clear_time,
        "clear_time_pretty": f"{clear_time//60000}:{(clear_time % 60000)//1000:02d}.{(clear_time % 1000):03d}",
        "clear_attempts": clear_attempts,
        "game_version": GAME_VERSION.get(game_version_raw, "Unknown"),
        "game_version_raw": game_version_raw,
        "timer": timer,
        "start_y": start_y,
        "goal_x": goal_x,
        "goal_y": goal_y,
        "clear_condition_type": "None",
        "clear_condition_type_raw": clear_condition,
        "clear_condition_magnitude": clear_condition_magnitude,
        "clear_condition": "None",
        "clear_condition_category": CLEAR_CONDITION_CATEGORY.get(clear_condition_category_raw, "None"),
        "clear_condition_category_raw": clear_condition_category_raw,
        "autoscroll_speed": AUTOSCROLL_SPEED.get(autoscroll_speed_raw, "x1"),
        "autoscroll_speed_raw": autoscroll_speed_raw,
        "autoscroll_type": AUTOSCROLL_TYPE.get(autoscroll_type_raw, "None"),
        "autoscroll_type_raw": autoscroll_type_raw,
        "orientation": ORIENTATION.get(orientation_raw, "Horizontal"),
        "orientation_raw": orientation_raw,
        "liquid_start_height": liquid_start_height,
        "liquid_end_height": liquid_end_height,
        "liquid_mode": LIQUID_MODE.get(liquid_mode_raw, "Static"),
        "liquid_speed": LIQUID_SPEED.get(liquid_speed_raw, "None"),
        "boundary_type": BOUNDARY_TYPE.get(boundary_type_raw, "Built Above Line"),
        "liquid_mode_raw": liquid_mode_raw,
        "liquid_speed_raw": liquid_speed_raw,
        "boundary_type_raw": boundary_type_raw,
        "right_boundary": boundary_right,
        "top_boundary": boundary_top,
        "left_boundary": boundary_left,
        "bottom_boundary": boundary_bottom,
        "object_count": object_count,
        "sound_effect_count": sound_effect_count,
        "snake_block_count": snake_block_count,
        "clear_pipe_count": clear_pipe_count,
        "piranha_creeper_count": piranha_creeper_count,
        "exclamation_mark_block_count": exclamation_mark_block_count,
        "track_count": track_count,
        "ground_count": ground_count,
        "icicle_count": ice_count,
        "upload_id": unk_upload_id,
        "creation_id": unk_creation_id,
        "gamever": unk_gamever,
        "management_flags": unk_management_flags,

        "objects": objects,
        "ground": ground,
        "tracks": tracks_raw,
        "snakes": snakes,
        "clear_pipes": clear_pipes,
        "piranha_creepers": piranha_creepers,
        "exclamation_blocks": exclamation_blocks,
        "track_blocks": track_blocks,
        "icicles": icicles,
        "sounds": sounds,
    }

    # Generate drawing instructions
    try:
        drawing_instructions = generate_drawing_instructions(level, plaintext, is_overworld)
    except Exception as e:
        print(f"  [WARN] drawing_instructions generation failed: {e}")
        drawing_instructions = []

    level["drawing_instructions"] = drawing_instructions

    if data_id is not None:
        level["data_id"] = data_id

    return level



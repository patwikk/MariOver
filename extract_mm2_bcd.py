def aes_cbc_encrypt(key_bytes: bytes, iv_bytes: bytes, plaintext: bytes) -> bytes:
    from Crypto.Cipher import AES
    cipher = AES.new(key_bytes, AES.MODE_CBC, iv_bytes)
    return cipher.encrypt(plaintext)



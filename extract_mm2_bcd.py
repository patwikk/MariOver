def parse_args():
    p = argparse.ArgumentParser(
        description="Extract .bcd and Toost-style JSON (with drawing_instructions) from mm2_level dataset")
    p.add_argument("--output_dir", "-o", default="./bcd_levels")
    p.add_argument("--limit", "-n", type=int, default=None)
    p.add_argument("--no_stream", action="store_true")
    p.add_argument("--ids", nargs="+", type=int, default=None)
    p.add_argument("--json", action="store_true")
    p.add_argument("--json_only", action="store_true")
    p.add_argument("--subworld", action="store_true",
                   help="Parse as subworld instead of overworld")
    return p.parse_args()



    def draw_track(self):
        Zm = self.Zm
        H = self.H
        gs = self.gamestyle

        for trk in self.level.get("tracks", []):
            t     = trk["type"]
            tx    = trk["x"]
            ty    = trk["y"]
            f0    = trk.get("f0", 0)
            f1    = trk.get("f1", 0)
            f2    = trk.get("f2", 0)

            if t == 0:
                path = gs | OBJ_T0
            elif t == 1:
                path = gs | OBJ_T1
            elif t < 10:
                path = gs | (OBJ_T2 + (t - 2) * 32768)
            else:
                path = gs | (OBJ_T10 + (t - 10) * 32768)

            if t < 8:
                self.draw_image(path, tx * Zm - Zm, (H-2) * Zm - ty * Zm, Zm*3, Zm*3)

                def tn(x, y):
                    if 0 <= x < len(self.track_node) and 0 <= y < len(self.track_node[0]):
                        return self.track_node[x][y]
                    return 0

                if t == 0:
                    if tn(tx+1+1, ty+1) == 1 and f0 == 0:
                        self.draw_image(gs | OBJ_T, tx*Zm+Zm, (H-1)*Zm-ty*Zm, Zm, Zm)
                    if tn(tx+1-1, ty+1) == 1 and f1 == 0:
                        self.draw_image(gs | OBJ_T, tx*Zm-Zm, (H-1)*Zm-ty*Zm, Zm, Zm)
                elif t == 1:
                    if tn(tx+1, ty+1+1) == 1 and f0 == 0:
                        self.draw_image(gs | OBJ_T, tx*Zm, (H-2)*Zm-ty*Zm, Zm, Zm)
                    if tn(tx+1, ty+1-1) == 1 and f1 == 0:
                        self.draw_image(gs | OBJ_T, tx*Zm, H*Zm-ty*Zm, Zm, Zm)
                elif t in (2, 4, 5):
                    if tn(tx+1+1, ty+1-1) == 1 and f0 == 0:
                        self.draw_image(gs | OBJ_T, tx*Zm+Zm, H*Zm-ty*Zm, Zm, Zm)
                    if tn(tx+1-1, ty+1+1) == 1 and f1 == 0:
                        self.draw_image(gs | OBJ_T, tx*Zm-Zm, (H-2)*Zm-ty*Zm, Zm, Zm)
                elif t in (3, 6, 7):
                    if tn(tx+1+1, ty+1+1) == 1 and f0 == 0:
                        self.draw_image(gs | OBJ_T, tx*Zm+Zm, (H-2)*Zm-ty*Zm, Zm, Zm)
                    if tn(tx+1-1, ty+1-1) == 1 and f1 == 0:
                        self.draw_image(gs | OBJ_T, tx*Zm-Zm, H*Zm-ty*Zm, Zm, Zm)
            else:
                # Y-track (type >= 8)
                self.draw_image(path, tx*Zm-Zm, (H-4)*Zm-ty*Zm, Zm*5, Zm*5)

                def tn(x, y):
                    if 0 <= x < len(self.track_node) and 0 <= y < len(self.track_node[0]):
                        return self.track_node[x][y]
                    return 0

                pt0 = self.track_ypt[t][0] if t < 17 else (0,0)
                pt1 = self.track_ypt[t][1] if t < 17 else (0,0)
                pt2 = self.track_ypt[t][2] if t < 17 else (0,0)

                if tn(tx+pt0[0], ty+pt0[1]) == 1 and f0 == 0:
                    self.draw_image(gs | OBJ_T,
                                   (tx-1+pt0[0])*Zm, (H-4)*Zm-(ty-pt0[1])*Zm, Zm, Zm)
                if tn(tx+pt1[0], ty+pt1[1]) == 1 and f1 == 0:
                    self.draw_image(gs | OBJ_T,
                                   (tx-1+pt1[0])*Zm, (H-4)*Zm-(ty-pt1[1])*Zm, Zm, Zm)
                if tn(tx+pt2[0], ty+pt2[1]) == 1 and f2 == 0:
                    self.draw_image(gs | OBJ_T,
                                   (tx-1+pt2[0])*Zm, (H-4)*Zm-(ty-pt2[1])*Zm, Zm, Zm)


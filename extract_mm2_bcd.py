MASK32 = 0xFFFFFFFF


def rand_init(s0, s1, s2, s3):
    cond = s0 | s1 | s2 | s3
    if cond:
        return [s0, s1, s2, s3]
    return [1, 0x6C078967, 0x714ACB41, 0x48077044]


def rand_gen(state):
    n = (state[0] ^ ((state[0] << 11) & MASK32)) & MASK32
    state[0] = state[1]
    n = (n ^ (n >> 8) ^ state[3] ^ (state[3] >> 19)) & MASK32
    state[1] = state[2]
    state[2] = state[3]
    state[3] = n
    return n


def gen_key(key_table, state):
    out = [0, 0, 0, 0]
    for i in range(4):
        for _ in range(4):
            out[i] = (out[i] << 8) & MASK32
            idx   = rand_gen(state) >> 26
            shift = (rand_gen(state) >> 27) & 24
            out[i] |= (key_table[idx] >> shift) & 0xFF
    return struct.pack("<4I", *out)


# ---------------------------------------------------------------------------
# Build encrypted .bcd
# ---------------------------------------------------------------------------

COURSE_FILE_SIZE = 0x5C000
HEADER_SIZE      = 0x10
TRAILER_SIZE     = 0x30
PAYLOAD_SIZE     = COURSE_FILE_SIZE - HEADER_SIZE - TRAILER_SIZE


def build_bcd(plaintext: bytes) -> bytes:
    if len(plaintext) != PAYLOAD_SIZE:
        raise ValueError(f"Plaintext must be {PAYLOAD_SIZE} bytes, got {len(plaintext)}")

    s0, s1, s2, s3 = 0xDEADBEEF, 0xCAFEBABE, 0x12345678, 0x9ABCDEF0
    iv_bytes = bytes([0x4E, 0x69, 0x6E, 0x74, 0x65, 0x6E, 0x64, 0x6F,
                      0x4D, 0x61, 0x6B, 0x65, 0x72, 0x32, 0x30, 0x31])

    state = rand_init(s0, s1, s2, s3)
    key_bytes = gen_key(COURSE_KEY_TABLE, state)
    ciphertext = aes_cbc_encrypt(key_bytes, iv_bytes, plaintext)

    trailer = iv_bytes + struct.pack("<4I", s0, s1, s2, s3) + b"\x00" * 16
    bcd = b"\x00" * HEADER_SIZE + ciphertext + trailer
    assert len(bcd) == COURSE_FILE_SIZE
    return bcd



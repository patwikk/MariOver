class BinaryReader:
    def __init__(self, data: bytes):
        self.data = data
        self.pos = 0

    def u1(self): return struct.unpack_from("<B", self.data, self._adv(1))[0]
    def s1(self): return struct.unpack_from("<b", self.data, self._adv(1))[0]
    def u2(self): return struct.unpack_from("<H", self.data, self._adv(2))[0]
    def s2(self): return struct.unpack_from("<h", self.data, self._adv(2))[0]
    def u4(self): return struct.unpack_from("<I", self.data, self._adv(4))[0]
    def s4(self): return struct.unpack_from("<i", self.data, self._adv(4))[0]
    def s8(self): return struct.unpack_from("<q", self.data, self._adv(8))[0]
    def skip(self, n: int): self.pos += n
    def _adv(self, n: int) -> int:
        p = self.pos; self.pos += n; return p

    def str_utf16le(self, size: int) -> str:
        raw = self.data[self.pos:self.pos + size]
        self.pos += size
        return raw.decode("utf-16-le", errors="replace").rstrip("\x00")


def parse_obj(r: BinaryReader) -> dict:
    obj = {
        "x": r.s4(),
        "y": r.s4(),
        "unk1": r.s2(),
        "w": r.u1(),
        "h": r.u1(),
        "flag": r.s4(),
        "cflag": r.s4(),
        "ex": r.s4(),
        "id": r.s2(),
        "cid": r.s2(),
        "lid": r.s2(),
        "sid": r.s2(),
    }
    obj["name"] = OBJ_ID.get(obj["id"], f"Unknown_{obj['id']}")
    obj["link_type"] = 0
    return obj


def parse_snake(r: BinaryReader) -> dict:
    index = r.u1()
    node_count = r.u1()
    r.u2()  # padding
    nodes = []
    for _ in range(node_count):
        nodes.append({
            "index": r.u2(),
            "direction": r.u2(),
            "unk1": r.u4()
        })
    return {"index": index, "node_count": node_count, "nodes": nodes}


def parse_clear_pipe(r: BinaryReader) -> dict:
    index = r.u1()
    node_count = r.u1()
    r.u2()  # padding
    nodes = []
    for _ in range(node_count):
        nodes.append({
            "type": r.u1(),
            "index": r.u1(),
            "x": r.u1(),
            "y": r.u1(),
            "w": r.u1(),
            "h": r.u1(),
            "unk1": r.u1(),
            "direction": r.u1()
        })
    return {"index": index, "node_count": node_count, "nodes": nodes}


def parse_piranha_creeper(r: BinaryReader) -> dict:
    unk1 = r.u1()
    index = r.u1()
    node_count = r.u1()
    r.u1()  # padding
    nodes = [r.u1() for _ in range(node_count)]
    return {"index": index, "node_count": node_count, "nodes": nodes}


def parse_exclamation_block(r: BinaryReader) -> dict:
    unk1 = r.u1()
    index = r.u1()
    node_count = r.u1()
    r.u1()  # padding
    nodes = []
    for _ in range(node_count):
        nodes.append({
            "unk1": r.u1(),
            "direction": r.u1(),
            "unk2": r.u2()
        })
    return {"index": index, "node_count": node_count, "nodes": nodes}


def parse_track_block(r: BinaryReader) -> dict:
    return parse_exclamation_block(r)


